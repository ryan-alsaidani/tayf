package com.tayf.app.data

import androidx.room.withTransaction
import com.tayf.app.core.DocType
import com.tayf.app.core.DocumentModel
import com.tayf.app.core.FileStore
import com.tayf.app.core.FilterType
import com.tayf.app.core.FolderModel
import com.tayf.app.core.PageModel
import com.tayf.app.core.Quad
import com.tayf.app.core.SortOrder
import com.tayf.app.data.db.DocumentEntity
import com.tayf.app.data.db.DocumentRow
import com.tayf.app.data.db.FolderEntity
import com.tayf.app.data.db.PageEntity
import com.tayf.app.data.db.PageFts
import com.tayf.app.data.db.TayfDatabase
import com.tayf.app.ocr.SearchText
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.map

class DocumentRepository(private val db: TayfDatabase, private val fileStore: FileStore) {

    private val docs = db.documentDao()
    private val pages = db.pageDao()
    private val folders = db.folderDao()
    private val fts = db.ftsDao()

    // ---- mapping ----

    private fun DocumentRow.toModel() = DocumentModel(
        id = id, name = name, folderId = folderId, createdAt = createdAt, updatedAt = updatedAt,
        isFavorite = isFavorite, isVault = isVault,
        docType = runCatching { DocType.valueOf(docType) }.getOrDefault(DocType.UNKNOWN),
        pageCount = pageCount, expiryDate = expiryDate
    )

    private fun PageEntity.toModel() = PageModel(
        id = id, documentId = documentId, position = position,
        originalPath = originalPath, processedPath = processedPath, thumbPath = thumbPath,
        quad = Quad(tlX, tlY, trX, trY, brX, brY, blX, blY),
        filter = runCatching { FilterType.valueOf(filter) }.getOrDefault(FilterType.ORIGINAL),
        brightness = brightness, contrast = contrast, rotation = rotation,
        ocrText = ocrText, ocrBlocksJson = ocrBlocksJson
    )

    private fun PageModel.toEntity(newId: Long, docId: Long, pos: Int) = PageEntity(
        id = newId, documentId = docId, position = pos,
        originalPath = originalPath, processedPath = processedPath, thumbPath = thumbPath,
        tlX = quad.tlX, tlY = quad.tlY, trX = quad.trX, trY = quad.trY,
        brX = quad.brX, brY = quad.brY, blX = quad.blX, blY = quad.blY,
        filter = filter.name, brightness = brightness, contrast = contrast, rotation = rotation,
        ocrText = ocrText, ocrBlocksJson = ocrBlocksJson
    )

    private fun sortModels(list: List<DocumentModel>, sort: SortOrder): List<DocumentModel> = when (sort) {
        SortOrder.DATE_DESC -> list.sortedByDescending { it.updatedAt }
        SortOrder.DATE_ASC -> list.sortedBy { it.updatedAt }
        SortOrder.NAME_ASC -> list.sortedWith(compareBy<DocumentModel, String>(String.CASE_INSENSITIVE_ORDER) { it.name })
        SortOrder.NAME_DESC -> list.sortedWith(compareBy<DocumentModel, String>(String.CASE_INSENSITIVE_ORDER) { it.name }).reversed()
    }

    // ---- observation ----

    /** folderId == null: all non-vault documents; otherwise only the documents of that folder (vault folder included). */
    fun observeDocuments(folderId: Long?, sort: SortOrder, favoritesOnly: Boolean): Flow<List<DocumentModel>> {
        val fav = if (favoritesOnly) 1 else 0
        val source = if (folderId == null) docs.observeAll(fav) else docs.observeInFolder(folderId, fav)
        return source.map { rows -> sortModels(rows.map { it.toModel() }, sort) }
    }

    fun observeFolders(includeVault: Boolean): Flow<List<FolderModel>> =
        folders.observeAll().map { list ->
            list.filter { includeVault || !it.isVault }.map { FolderModel(it.id, it.name, it.isVault, it.createdAt) }
        }

    fun observeDocument(id: Long): Flow<DocumentModel?> = docs.observeOne(id).map { it?.toModel() }

    fun observePages(documentId: Long): Flow<List<PageModel>> =
        pages.observeByDocument(documentId).map { list -> list.map { it.toModel() } }

    // ---- reads ----

    suspend fun getDocument(id: Long): DocumentModel? = docs.getRow(id)?.toModel()
    suspend fun getPages(documentId: Long): List<PageModel> = pages.getByDocument(documentId).map { it.toModel() }
    suspend fun getPage(pageId: Long): PageModel? = pages.getById(pageId)?.toModel()

    // ---- documents ----

    suspend fun createDocument(name: String, folderId: Long?, docType: DocType, isVault: Boolean = false): Long {
        val now = System.currentTimeMillis()
        return docs.insert(
            DocumentEntity(
                name = name, folderId = folderId, createdAt = now, updatedAt = now,
                isFavorite = false, isVault = isVault, docType = docType.name, expiryDate = null
            )
        )
    }

    /** id is ignored (autogenerated); position = last. */
    suspend fun addPage(documentId: Long, page: PageModel): Long = db.withTransaction {
        val pos = (pages.maxPosition(documentId) ?: -1) + 1
        val id = pages.insert(page.toEntity(0, documentId, pos))
        docs.touch(documentId, System.currentTimeMillis())
        id
    }

    suspend fun updatePage(page: PageModel) {
        val existing = pages.getById(page.id) ?: return
        pages.update(page.toEntity(page.id, existing.documentId, existing.position))
        docs.touch(existing.documentId, System.currentTimeMillis())
    }

    suspend fun deletePages(pageIds: List<Long>) {
        if (pageIds.isEmpty()) return
        val entities = pages.getByIds(pageIds)
        db.withTransaction {
            fts.delete(pageIds)
            pages.deleteByIds(pageIds)
            entities.map { it.documentId }.distinct().forEach { renumber(it) }
        }
        entities.forEach { deleteFiles(it) }
    }

    suspend fun reorderPages(documentId: Long, orderedPageIds: List<Long>) = db.withTransaction {
        orderedPageIds.forEachIndexed { index, id -> pages.setPosition(id, index) }
        docs.touch(documentId, System.currentTimeMillis())
    }

    suspend fun renameDocument(id: Long, newName: String) {
        docs.rename(id, newName.trim().ifEmpty { return }, System.currentTimeMillis())
    }

    suspend fun setFavorite(id: Long, favorite: Boolean) = docs.setFavorite(id, favorite)

    /** Moving into a vault folder marks the document as vault; moving out clears the flag. */
    suspend fun moveDocument(id: Long, folderId: Long?) {
        val isVault = folderId?.let { folders.get(it)?.isVault } ?: false
        docs.setFolder(id, folderId, isVault, System.currentTimeMillis())
    }

    suspend fun setDocType(id: Long, type: DocType) = docs.setDocType(id, type.name)
    suspend fun setExpiry(id: Long, expiryDate: Long?) = docs.setExpiry(id, expiryDate)

    suspend fun deleteDocument(id: Long) {
        val all = pages.getByDocument(id)
        db.withTransaction {
            fts.delete(all.map { it.id })
            docs.delete(id)
        }
        all.forEach { deleteFiles(it) }
    }

    /** Moves the given pages into a new document and returns its id. */
    suspend fun splitDocument(id: Long, pageIdsForNewDoc: List<Long>, newName: String): Long = db.withTransaction {
        val source = docs.getRow(id) ?: return@withTransaction -1L
        val now = System.currentTimeMillis()
        val newId = docs.insert(
            DocumentEntity(
                name = newName, folderId = source.folderId, createdAt = now, updatedAt = now,
                isFavorite = false, isVault = source.isVault, docType = source.docType, expiryDate = null
            )
        )
        val ordered = pages.getByDocument(id).filter { it.id in pageIdsForNewDoc }
        ordered.forEachIndexed { index, p -> pages.moveToDocument(p.id, newId, index) }
        renumber(id)
        newId
    }

    /** Appends the pages of [sourceId] to [targetId] and deletes the source document. */
    suspend fun mergeInto(targetId: Long, sourceId: Long) {
        if (targetId == sourceId) return
        db.withTransaction {
            var pos = (pages.maxPosition(targetId) ?: -1) + 1
            pages.getByDocument(sourceId).forEach { p -> pages.moveToDocument(p.id, targetId, pos++) }
            docs.touch(targetId, System.currentTimeMillis())
            docs.delete(sourceId)
        }
    }

    // ---- folders ----

    suspend fun createFolder(name: String, isVault: Boolean = false): Long =
        folders.insert(FolderEntity(name = name.trim(), isVault = isVault, createdAt = System.currentTimeMillis()))

    suspend fun renameFolder(id: Long, name: String) = folders.rename(id, name.trim())

    /** Documents move to root. Vault folders cannot be deleted. */
    suspend fun deleteFolder(id: Long) {
        val folder = folders.get(id) ?: return
        if (folder.isVault) return
        db.withTransaction {
            docs.clearFolder(id)
            folders.delete(id)
        }
    }

    suspend fun listExpiring(withinDays: Int): List<DocumentModel> {
        val limit = System.currentTimeMillis() + withinDays.toLong() * 24L * 60L * 60L * 1000L
        return docs.listExpiring(limit).map { it.toModel() }
    }

    suspend fun saveOcr(pageId: Long, text: String, blocksJson: String) = db.withTransaction {
        pages.setOcr(pageId, text, blocksJson)
        fts.upsert(PageFts(pageId, SearchText.normalize(text)))
    }

    /** Clears OCR data of a page (after its image changed). */
    suspend fun clearOcr(pageId: Long) = db.withTransaction {
        pages.setOcr(pageId, null, null)
        fts.delete(listOf(pageId))
    }

    // ---- helpers ----

    private suspend fun renumber(docId: Long) {
        pages.getByDocument(docId).forEachIndexed { index, p -> if (p.position != index) pages.setPosition(p.id, index) }
        docs.touch(docId, System.currentTimeMillis())
    }

    private fun deleteFiles(p: PageEntity) {
        fileStore.deleteQuietly(p.originalPath)
        fileStore.deleteQuietly(p.processedPath)
        fileStore.deleteQuietly(p.thumbPath)
    }
}
